        "password=" + fill(","),
        fill('password=\\"'),
        fill('\\"password\\": \\"a\\"'),
        fill("password" + "\\" * 40),
        fill("password" + " " * 9),
        fill("Authorization: "),
        fill("Authorization: a\n"),
        fill("Cookie: ,\n"),
        fill("b'"),
        fill("a" * 65535 + "="),
        'password="' + fill("\\"),
        fill("password=['"),
        fill('password=[\\"'),
        "password=[" + fill("'"),
        "password=[" + fill("\\"),
